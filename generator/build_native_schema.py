"""Write native/src/spa_schema.h: the binary layouts of the DB tables the native module reads, for every
version the RPFM schema (schema_wh3.ron) knows.

The game stores a DB table as fragments (db/<table>_tables/<name>), each starting with its version
number; the module looks up the field list for that version here. A fragment of a version that is not
in this file is skipped (with a warning in the result), so after a game patch that changes one of these
tables: download a fresh schema_wh3.ron from https://github.com/Frodo45127/rpfm-schemas, run this, then
generator/build_native.py.

Usage (from the project folder):
  python generator/build_native_schema.py [--schema generator/schema_wh3.ron]
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import tw_db  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "native", "src", "spa_schema.h")

# the tables the mod's live data is built from (the same ones generator/build_data.py bakes)
TABLES = [
    "character_skill_nodes_tables",
    "character_skill_node_links_tables",
    "character_skill_nodes_skill_locks_tables",
    "character_skill_node_sets_tables",
    "character_skill_node_set_items_tables",
    "character_skills_tables",
    "character_skills_to_level_reached_criterias_tables",
    "character_experience_skill_tiers_tables",
    "character_skill_level_details_tables",
    "character_skill_level_to_effects_junctions_tables",
]

TYPES = {
    "Boolean": "FT_BOOL", "F32": "FT_F32", "F64": "FT_F64", "I16": "FT_I16", "I32": "FT_I32", "I64": "FT_I64",
    "ColourRGB": "FT_COLOUR", "StringU8": "FT_S8", "StringU16": "FT_S16",
    "OptionalI16": "FT_OI16", "OptionalI32": "FT_OI32", "OptionalI64": "FT_OI64",
    "OptionalStringU8": "FT_OS8", "OptionalStringU16": "FT_OS16",
    "SequenceU16": "FT_SEQ16", "SequenceU32": "FT_SEQ32",
}


def ftype(field):
    t = field["field_type"]
    return t if isinstance(t, str) else t.name


def c_ident(text):
    return "".join(c if c.isalnum() else "_" for c in text)


def emit_fields(lines, name, fields):
    """Write the field array `name` (and the arrays of nested sequences first); returns its length."""
    nested = {}
    for i, f in enumerate(fields):
        t = ftype(f)
        if t not in TYPES:
            sys.exit(f"{name}: field {f['name']} has type {t}, which the native module can't read")
        if t.startswith("Sequence"):
            sub = f["field_type"].args[0]
            sub_name = f"{name}_{i}_{c_ident(f['name'])}"
            nested[i] = (sub_name, emit_fields(lines, sub_name, sub["fields"]))
    lines.append(f"static const spa_field {name}[] = {{")
    for i, f in enumerate(fields):
        t = TYPES[ftype(f)]
        key = 1 if f.get("is_key") else 0
        if i in nested:
            sub_name, n = nested[i]
            lines.append(f'\t{{ "{f["name"]}", {t}, {key}, {n}, {sub_name} }},')
        else:
            lines.append(f'\t{{ "{f["name"]}", {t}, {key}, 0, NULL }},')
    lines.append("};")
    return len(fields)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--schema", default=os.path.join(ROOT, "generator", "schema_wh3.ron"))
    a = ap.parse_args()
    schema = tw_db.Schema(a.schema)
    lines = [
        "/* GENERATED by generator/build_native_schema.py from schema_wh3.ron - do not edit by hand. */",
        "#ifndef SPA_SCHEMA_H",
        "#define SPA_SCHEMA_H",
        "",
        '#include "spa_native.h"',
        "",
    ]
    tables = []
    for t in TABLES:
        defs = sorted(schema.defs.get(t, []), key=lambda d: d["version"])
        if not defs:
            sys.exit(f"{t} is not in the schema")
        for d in defs:
            name = f"F_{c_ident(t)}_v{d['version']}"
            n = emit_fields(lines, name, d["fields"])
            tables.append((t, d["version"], n, name))
        lines.append("")
    lines.append("static const spa_table_def SPA_TABLE_DEFS[] = {")
    for t, v, n, name in tables:
        lines.append(f'\t{{ "{t}", {v}, {n}, {name} }},')
    lines.append("};")
    lines.append(f"#define SPA_TABLE_DEF_COUNT {len(tables)}")
    lines.append("")
    lines.append("#endif")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {OUT}: {len(tables)} table versions of {len(TABLES)} tables")


if __name__ == "__main__":
    main()
