"""Check Skill Pre-Allocation against its published checksums (SHA256SUMS.txt).

Give it any of:
  - the mod's pack, for example the Workshop copy
    "C:/Program Files (x86)/Steam/steamapps/workshop/content/1142710/3819368555/skill_preallocation.pack":
    checks the whole pack (every script in it) and the native module it carries, before the game ever
    writes the module out;
  - the DLL the mod wrote into the game's folder, skill_preallocation_native.dll;
  - src/script/skill_preallocation/native_bin.lua from this repository (the DLL, written as Lua).

It prints what it found and whether it matches SHA256SUMS.txt (next to this file, at the top of the
repository, or --sums FILE). For the DLL it also prints every Windows function it imports, the function
it offers, and the function names it could look up while running. It ends with "All good" only when
everything given matches a published checksum.

  python generator/verify_native.py <file> [<file> ...] [--sums SHA256SUMS.txt] [--extract out.dll]

--extract (with one file) writes the DLL carried in a pack or native_bin.lua out as a file, to look at it
with other tools.
Needs Python 3 only: no other packages; nothing is changed or sent anywhere.
"""
import argparse
import hashlib
import os
import re
import struct
import sys
import textwrap

MODULE = "skill_preallocation_native"
BIN_PATH = "script/skill_preallocation/native_bin.lua"
HERE = os.path.dirname(os.path.abspath(__file__))
SUMS_NAME = "SHA256SUMS.txt"


# ---------------------------------------------------------------- native_bin.lua, exactly as build_native.py writes it
ESCAPES = {0x0A: b"\\n", 0x0D: b"\\r", 0x22: b'\\"', 0x5C: b"\\\\"}


def lua_string(data):
    """data as a Lua string literal: printable bytes as they are, the rest as decimal escapes."""
    out = bytearray(b'"')
    for i, byte in enumerate(data):
        if byte in ESCAPES:
            out += ESCAPES[byte]
        elif 32 <= byte <= 126:
            out.append(byte)
        else:
            # a decimal escape takes up to three digits: pad it when a digit follows
            nxt = data[i + 1] if i + 1 < len(data) else None
            out += (b"\\%03d" % byte) if (nxt is not None and 48 <= nxt <= 57) else (b"\\%d" % byte)
    out += b'"'
    return bytes(out)


def bin_lua_text(dll, version):
    """The whole of native_bin.lua for this DLL (build_native.py writes it with this function)."""
    digest = hashlib.sha256(dll).hexdigest()
    return (b"-- GENERATED by generator/build_native.py from native/src - do not edit by hand.\n"
            b"-- The mod's native module (Windows x64 DLL), written into the game's folder by skill_preallocation_live.lua.\n"
            + ("-- sha256 %s, %d bytes\n" % (digest, len(dll))).encode()
            + b'return { module = "' + MODULE.encode() + b'", version = "' + version.encode() + b'", sha256 = "'
            + digest.encode() + b'", size = ' + str(len(dll)).encode() + b", data = " + lua_string(dll) + b" }\n")


SIMPLE = {"n": 10, "r": 13, "t": 9, "a": 7, "b": 8, "f": 12, "v": 11, "\\": 92, '"': 34, "'": 39, "\n": 10}


def read_lua_string(text, start):
    """The bytes of the Lua string literal that opens at text[start] (a double quote), and where it ends."""
    out = bytearray()
    i = start + 1
    while True:
        if i >= len(text):
            raise ValueError("the string never ends")
        c = text[i]
        if c == 34:
            return bytes(out), i + 1
        if c != 92:
            out.append(c)
            i += 1
            continue
        nxt = chr(text[i + 1]) if i + 1 < len(text) else ""
        if nxt.isdigit():
            j = i + 1
            while j < i + 4 and j < len(text) and chr(text[j]).isdigit():
                j += 1
            out.append(int(text[i + 1:j]))
            i = j
        elif nxt in SIMPLE:
            out.append(SIMPLE[nxt])
            i += 2
        else:
            raise ValueError("unknown escape")


def from_bin_lua(text):
    """The DLL carried in native_bin.lua, and its module version. The file must be exactly what
    build_native.py writes for that DLL: anything else in it (other code, a second copy in a comment...)
    is refused."""
    m = re.match(rb'-- GENERATED[^\n]*\n--[^\n]*\n--[^\n]*\nreturn \{ module = "' + MODULE.encode()
                 + rb'", version = "([0-9A-Za-z.\-]+)", sha256 = "[0-9a-f]{64}", size = \d+, data = "', text)
    if not m:
        raise ValueError("not the file build_native.py writes")
    dll, _ = read_lua_string(text, m.end() - 1)
    version = m.group(1).decode()
    if bin_lua_text(dll, version) != text:
        raise ValueError("not exactly the file build_native.py writes for the DLL in it")
    return dll, version


# ---------------------------------------------------------------- a .pack: its index and files
def pack_entries(data):
    """[(path with '/', stored bytes, compressed)] of a PFH5/PFH4 pack."""
    if len(data) < 28 or data[:3] != b"PFH" or data[3:4] not in (b"4", b"5"):
        raise ValueError("not a Total War pack")
    pfh5 = data[3:4] == b"5"
    ptype, dep_count, dep_size, count, index_size = struct.unpack_from("<5I", data, 4)
    flags = ptype & ~0xF
    if flags & 0x90:
        raise ValueError("this pack's index is encrypted")
    pos = 28 + (20 if flags & 0x100 else 0) + dep_size
    offset = pos + index_size
    end_index = offset
    out = []
    for _ in range(count):
        size = struct.unpack_from("<I", data, pos)[0]
        pos += 4 + (4 if flags & 0x40 else 0)
        compressed = 0
        if pfh5:
            compressed = data[pos]
            pos += 1
        end = data.index(b"\0", pos, end_index)
        name = data[pos:end].decode("latin-1").replace("\\", "/")
        pos = end + 1
        if offset + size > len(data):
            raise ValueError("the pack is cut short")
        out.append((name, data[offset:offset + size], compressed))
        offset += size
    return out


# ---------------------------------------------------------------- the DLL: what it links to and offers
def pe_tables(dll):
    """A Windows DLL's machine type, its import table [(library, [function, ...])] and the names it exports."""
    if dll[:2] != b"MZ" or len(dll) < 0x40:
        raise ValueError("not a Windows DLL")
    pe = struct.unpack_from("<I", dll, 0x3C)[0]
    if dll[pe:pe + 4] != b"PE\0\0":
        raise ValueError("not a Windows DLL")
    machine = struct.unpack_from("<H", dll, pe + 4)[0]
    opt = pe + 24
    pe64 = struct.unpack_from("<H", dll, opt)[0] == 0x20B
    dirs = opt + (112 if pe64 else 96)
    nsec = struct.unpack_from("<H", dll, pe + 6)[0]
    first = opt + struct.unpack_from("<H", dll, pe + 20)[0]
    secs = [struct.unpack_from("<IIII", dll, first + 40 * i + 8) for i in range(nsec)]

    def off(rva):
        for size, addr, raw_size, ptr in secs:
            if addr <= rva < addr + max(size, raw_size):
                return rva - addr + ptr
        raise ValueError("bad address %x" % rva)

    def cstr(at):
        return dll[at:dll.index(b"\0", at)].decode("ascii")

    imports, exports = [], []
    imp = struct.unpack_from("<I", dll, dirs + 8)[0]
    at = off(imp) if imp else None
    thunk_size, by_ordinal = (8, 1 << 63) if pe64 else (4, 1 << 31)
    while at is not None and struct.unpack_from("<I", dll, at + 12)[0]:
        library = cstr(off(struct.unpack_from("<I", dll, at + 12)[0]))
        functions = []
        thunk = off(struct.unpack_from("<I", dll, at)[0] or struct.unpack_from("<I", dll, at + 16)[0])
        while True:
            v = struct.unpack_from("<Q" if pe64 else "<I", dll, thunk)[0]
            if not v:
                break
            functions.append("#%d" % (v & 0xFFFF) if v & by_ordinal else cstr(off(v & 0x7FFFFFFF) + 2))
            thunk += thunk_size
        imports.append((library, functions))
        at += 20
    exp = struct.unpack_from("<I", dll, dirs)[0]
    if exp:
        e = off(exp)
        n = struct.unpack_from("<I", dll, e + 24)[0]
        names = off(struct.unpack_from("<I", dll, e + 32)[0])
        exports = [cstr(off(struct.unpack_from("<I", dll, names + 4 * i)[0])) for i in range(n)]
    return machine, imports, exports


# ---------------------------------------------------------------- the published checksums
def find_sums(given):
    if given:
        return given
    for p in (os.path.join(HERE, SUMS_NAME), os.path.join(os.path.dirname(HERE), SUMS_NAME)):
        if os.path.exists(p):
            return p
    return None


def read_sums(path):
    """{"dll": {sha256: (mod version, module version)}, "pack": {sha256: mod version}}"""
    sums = {"dll": {}, "pack": {}}
    for line in open(path, encoding="utf-8"):
        parts = line.split("#", 1)[0].split()
        if len(parts) == 4 and parts[0] == "dll" and re.fullmatch(r"[0-9a-fA-F]{64}", parts[3]):
            sums["dll"][parts[3].lower()] = (parts[1], parts[2])
        elif len(parts) == 3 and parts[0] == "pack" and re.fullmatch(r"[0-9a-fA-F]{64}", parts[2]):
            sums["pack"][parts[2].lower()] = parts[1]
    if not sums["dll"] and not sums["pack"]:
        raise ValueError("no checksums in " + path + " (lines like 'dll 0.19.0 1.0.1 <sha256>')")
    return sums


def looked_up_names(dll, imports_found):
    """The names in the DLL that it could look up at run time (GetProcAddress takes a name): the Lua
    functions (lua_*), and any other name that looks like a Windows function (WriteFile, ...)."""
    strings = set(m.decode() for m in re.findall(rb"[A-Za-z_][A-Za-z0-9_]{3,}", dll))
    lua = sorted(n for n in strings if re.fullmatch(r"luaL?_[a-z]+", n))
    windows_like = sorted(n for n in strings if re.fullmatch(r"(?:[A-Z][a-z]{2,}){2,}(?:[AW]|Ex)?", n) and n not in imports_found)
    return lua, windows_like


def check_dll(dll, sums, label):
    """True when the DLL is a published one."""
    digest = hashlib.sha256(dll).hexdigest()
    print("   %s: SHA-256 %s, %d bytes" % (label, digest, len(dll)))
    ok = digest in sums["dll"]
    if ok:
        mod, native = sums["dll"][digest]
        print("   MATCHES " + SUMS_NAME + ": the native module " + native + " of Skill Pre-Allocation " + mod)
    else:
        print("   NOT a published DLL: its checksum isn't in " + SUMS_NAME)
    try:
        machine, imports, exports = pe_tables(dll)
        print("   a Windows x64 DLL" if machine == 0x8664 else "   machine type %x" % machine)
        print("   links to: " + ", ".join(library for library, _ in imports))
        print("   the Windows functions it uses (its whole import table, %d):" % sum(len(f) for _, f in imports))
        for library, functions in imports:
            print(textwrap.fill(", ".join(functions), width=100, initial_indent="     %s: " % library,
                                subsequent_indent=" " * 7, break_on_hyphens=False))
        print("   offers:   " + ", ".join(exports))
        lua, windows_like = looked_up_names(dll, set(f for _, functions in imports for f in functions))
        print("   names it can look up while running (GetProcAddress): %d of the game's Lua functions (%s ... %s)"
              % (len(lua), lua[0] if lua else "-", lua[-1] if lua else "-"))
        print("   other Windows-style function names in it: " + (", ".join(windows_like) if windows_like else "none"))
    except (ValueError, struct.error, IndexError) as e:
        print("   can't read it as a Windows DLL: %s" % e)
        ok = False
    return ok


def check(path, sums, extract):
    print("== " + path)
    data = open(path, "rb").read()
    dll = None
    ok = True
    if data[:3] == b"PFH":
        digest = hashlib.sha256(data).hexdigest()
        print("   the pack: SHA-256 " + digest)
        if digest in sums["pack"]:
            print("   MATCHES " + SUMS_NAME + ": the published pack of Skill Pre-Allocation " + sums["pack"][digest]
                  + " (every file in it is the published one)")
        else:
            ok = False
            print("   NOT a published pack: its checksum isn't in " + SUMS_NAME + " (its files may differ from the published ones)")
        found = [e for e in pack_entries(data) if e[0].lower() == BIN_PATH]
        if len(found) != 1:
            print("   it carries %s copies of %s: expected one" % (len(found), BIN_PATH))
            return False
        name, stored, compressed = found[0]
        if compressed:
            print("   " + BIN_PATH + " is compressed in it (the mod's own packs aren't)")
            return False
        dll, version = from_bin_lua(stored)
        print("   it carries the native module " + version + " (" + BIN_PATH + ", exactly as build_native.py writes it)")
        ok &= check_dll(dll, sums, "the DLL in it")
    elif data[:2] == b"MZ":
        ok &= check_dll(data, sums, "the DLL")
    else:
        dll, version = from_bin_lua(data)
        print("   the native module " + version + " written as Lua, exactly as build_native.py writes it")
        ok &= check_dll(dll, sums, "the DLL in it")
    if extract and dll is not None:
        open(extract, "wb").write(dll)
        print("   the DLL written to " + extract)
    return ok


def main():
    ap = argparse.ArgumentParser(description="Check Skill Pre-Allocation against SHA256SUMS.txt.")
    ap.add_argument("files", nargs="+", help="the mod's .pack, the DLL, or native_bin.lua")
    ap.add_argument("--sums", help="the published checksums (default: " + SUMS_NAME + " next to this file or at the top of the repository)")
    ap.add_argument("--extract", help="write the DLL carried in the pack or native_bin.lua to this file (one file only)")
    a = ap.parse_args()
    if a.extract and len(a.files) != 1:
        sys.exit("--extract takes one file to check")
    sums_path = find_sums(a.sums)
    if not sums_path or not os.path.exists(sums_path):
        sys.exit("Can't check: " + SUMS_NAME + " not found (download it next to this file, or give --sums)")
    try:
        sums = read_sums(sums_path)
    except (OSError, ValueError) as e:
        sys.exit("Can't check: %s" % e)
    results = []
    for f in a.files:
        try:
            results.append(check(f, sums, a.extract))
        except OSError as e:
            print("== %s\n   can't read it: %s" % (f, e.strerror or e))
            results.append(False)
        except (ValueError, struct.error, IndexError) as e:
            print("   doesn't check out: %s" % e)
            results.append(False)
    print("\nAll good: everything matches the published checksums." if all(results) else "\nSomething doesn't match: see above.")
    sys.exit(0 if all(results) else 1)


if __name__ == "__main__":
    main()
